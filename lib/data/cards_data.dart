  code: code,
  continent: continent,
  flag: flag,
  subtitle: subtitle,
  intro: intro,
  sortOrder: sortOrder,
  isActive: true,
  totalCards: _countrySeeds[id]!.length,
);

List<CollectibleCard> _buildCountryCards(
  AlbumCountry country,
  List<_CardSeed> seeds,
) => List.generate(seeds.length, (index) {
  final seed = seeds[index];
  final cardNumber = index + 1;
  final id = '${country.id}_${seed.slug}';
  final rarity = seed.rarity ?? _defaultRarity(seed.category);
  return CollectibleCard(
    id: id,
    countryId: country.id,
    name: seed.name,
    description: _descriptionFor(seed, country.name),
    rarity: rarity,
    category: seed.category,
    imagePath:
        'assets/images/cards/${country.id}/${rarity.toLowerCase()}/$id.webp',
    cardNumber: cardNumber,
    catalogNumber: '${country.code}-${cardNumber.toString().padLeft(3, '0')}',
    isActive: true,
    sortOrder: cardNumber * 10,
    isPlaceholderImage: !approvedCardArtIds.contains(id),
  );
});

String _defaultRarity(String category) => switch (category) {
  CardCategory.city => CardRarity.common,
  CardCategory.flag || CardCategory.currency => CardRarity.rare,
  CardCategory.landmark => CardRarity.epic,
  _ => CardRarity.rare,
};

String _descriptionFor(
  _CardSeed seed,
  String country,
) => switch (seed.category) {
  CardCategory.city =>
    '${seed.name} integra a seleção de cidades essenciais do capítulo $country.',
  CardCategory.landmark =>
    '${seed.name} é um dos monumentos e lugares marcantes selecionados para representar $country.',
  CardCategory.nature =>
    '${seed.name} representa a riqueza natural e as grandes paisagens de $country.',
  CardCategory.animal =>
    '${seed.name} faz parte da fauna e dos símbolos naturais associados a $country.',
  CardCategory.person =>
    '${seed.name} é uma das personalidades escolhidas para contar a história e a cultura de $country.',
  CardCategory.mythology =>
    '${seed.name} pertence ao imaginário, às lendas e à mitologia presentes no capítulo $country.',
  CardCategory.currency =>
    '${seed.name} é a moeda representada na coleção de $country.',
  CardCategory.flag =>
    '${seed.name} é um dos principais símbolos nacionais de $country.',
  _ =>
    '${seed.name} foi selecionado como um elemento marcante da história e da cultura de $country.',
};

