class CardCatalog {
  CardCatalog._();

  static final Map<String, CollectibleCard> _cardsById = {
    for (final card in collectibleCards) card.id: card,
  };
  static final Map<String, AlbumCountry> _countriesById = {
    for (final country in albumCountries) country.id: country,
  };
  static final Map<String, List<CollectibleCard>> _cardsByCountry =
      _groupCards();
  static final Map<String, List<AlbumCountry>> _countriesByContinent =
      _groupCountries();

  static CollectibleCard? cardById(String id) => _cardsById[id];
  static AlbumCountry? countryById(String id) => _countriesById[id];

  static List<CollectibleCard> cardsForCountry(String countryId) =>
      _cardsByCountry[countryId] ?? const [];

  static List<AlbumCountry> countriesForContinent(String continent) =>
      _countriesByContinent[continent] ?? const [];

  static Map<String, List<CollectibleCard>> _groupCards() {
    final grouped = <String, List<CollectibleCard>>{};
    for (final card in collectibleCards.where((card) => card.isActive)) {
      grouped.putIfAbsent(card.countryId, () => []).add(card);
    }
    return {
      for (final entry in grouped.entries)
        entry.key: List.unmodifiable(
          entry.value..sort((a, b) => a.sortOrder.compareTo(b.sortOrder)),
        ),
    };
  }

  static Map<String, List<AlbumCountry>> _groupCountries() {
    final grouped = <String, List<AlbumCountry>>{};
    for (final country in albumCountries.where((country) => country.isActive)) {
      grouped.putIfAbsent(country.continent, () => []).add(country);
    }
    return {
      for (final entry in grouped.entries)
        entry.key: List.unmodifiable(
          entry.value..sort((a, b) => a.sortOrder.compareTo(b.sortOrder)),
        ),
    };
  }
}
